"""
MQL5 export.

This writes scaffolding: inputs matching your spec, the detector translated as
faithfully as the language allows, and clearly marked stubs where you must
supply broker-specific handling. It is not a finished EA and does not pretend
to be. Anything that claims to turn a statistical spec into a live expert
advisor without human work is skipping the part where money is lost.
"""

from __future__ import annotations

from datetime import datetime, timezone

from .spec import Spec

_ORDER_BLOCK_DETECT = r"""
//--- Order block detection -------------------------------------------------
// Returns true and fills zoneLow/zoneHigh when a zone confirmed on bar `shift`.
bool DetectOrderBlock(int shift, double &zoneLow, double &zoneHigh, int &bias)
{
   double atrBuf[];
   if(CopyBuffer(gAtrHandle, 0, shift+InpDisplacementBars, 2, atrBuf) <= 0) return false;
   double refAtr = atrBuf[0];
   if(refAtr <= 0) return false;

   int start = shift + InpDisplacementBars - 1;
   double move = iClose(_Symbol, InpTimeframe, shift) - iOpen(_Symbol, InpTimeframe, start);
   double size = MathAbs(move) / refAtr;
   if(size < InpDisplacementATR) return false;
   bool bull = move > 0;

   if(InpRequireSwingBreak)
   {
      int hi = iHighest(_Symbol, InpTimeframe, MODE_HIGH, InpSwingLookback, start+1);
      int lo = iLowest(_Symbol, InpTimeframe, MODE_LOW,  InpSwingLookback, start+1);
      if(bull  && !(iHigh(_Symbol,InpTimeframe,shift) > iHigh(_Symbol,InpTimeframe,hi))) return false;
      if(!bull && !(iLow(_Symbol,InpTimeframe,shift)  < iLow(_Symbol,InpTimeframe,lo)))  return false;
   }

   // last opposite-close candle before the move
   int found = -1;
   for(int j = start+1; j <= start + InpSwingLookback + 5; j++)
   {
      double o = iOpen(_Symbol, InpTimeframe, j);
      double c = iClose(_Symbol, InpTimeframe, j);
      if((bull && c < o) || (!bull && c > o)) { found = j; break; }
   }
   if(found < 0) return false;

   double o = iOpen(_Symbol, InpTimeframe, found);
   double c = iClose(_Symbol, InpTimeframe, found);
   if(InpZoneFromWick)
   { zoneLow = iLow(_Symbol,InpTimeframe,found); zoneHigh = iHigh(_Symbol,InpTimeframe,found); }
   else
   { zoneLow = MathMin(o,c); zoneHigh = MathMax(o,c); }

   bias = bull ? 1 : -1;
   return zoneHigh > zoneLow;
}
"""

